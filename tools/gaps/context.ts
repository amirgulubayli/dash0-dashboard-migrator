// The GapContext of this checkout: the rule catalog, probes and mapping tables from src/ and mappings/, owners from
// the workspace NOTES.md. Reading src/ from tools/ is fine; the other direction is forbidden (tests/tools/boundary).
import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { parse } from "yaml";
import { CATALOG, PROBES, resolveCode } from "../../src/rules/index.js";
import { loadOwners } from "../lib/notes.js";
import type { CatalogRule, GapContext } from "./gaps.js";

export function catalogRules(): CatalogRule[] {
  return CATALOG.map((r) => ({
    id: r.id,
    status: r.status,
    state: r.state,
    priority: r.priority,
    owner: r.owner,
    match: r.match,
    emit: r.emit,
    requires: [...r.requires],
    ...(r.epsilon !== undefined && { epsilon: r.epsilon }),
    ...(r.note !== undefined && { note: r.note }),
    ...(r.findingCode !== undefined && { findingCode: r.findingCode }),
  }));
}

export function loadContext(root: string): GapContext & { notesFile: string | null } {
  const catDir = join(root, "src", "rules", "catalog");
  const texts = readdirSync(catDir)
    .filter((f) => f.endsWith(".ts"))
    .sort()
    .map((f) => ({ file: `src/rules/catalog/${f}`, text: readFileSync(join(catDir, f), "utf8") }));
  const rules = catalogRules();
  const catalogFile: Record<string, string> = {};
  for (const r of rules) {
    const hit = texts.find((t) => t.text.includes(`"${r.id}"`));
    if (hit) catalogFile[r.id] = hit.file;
  }
  const ddDir = join(root, "mappings", "datadog");
  const mappingTables = readdirSync(ddDir)
    .filter((f) => f.endsWith(".yaml"))
    .sort()
    .map((f) => {
      const text = readFileSync(join(ddDir, f), "utf8");
      const doc = (parse(text) ?? {}) as { metrics?: Record<string, unknown> };
      const prefixes = [...new Set(Object.keys(doc.metrics ?? {}).map((k) => k.split(".")[0]!))].sort();
      const gen = /^#\s*GENERATED by (\S+)/m.exec(text)?.[1]?.replace(/\.$/, "");
      return { file: `mappings/datadog/${f}`, prefixes, ...(gen && { generatedBy: gen }) };
    });
  const { file, rows } = loadOwners(root);
  return {
    rules,
    probes: Object.fromEntries(Object.entries(PROBES).map(([k, p]) => [k, { question: p.question, answer: p.answer }])),
    catalogFile,
    resolve: (code) => resolveCode(code)?.id,
    mappingTables,
    owners: rows,
    notesFile: file,
  };
}
